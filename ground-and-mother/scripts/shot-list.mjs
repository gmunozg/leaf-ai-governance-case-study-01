// Writes PHOTOGRAPHY.md: every photograph the site needs, with its art-direction brief and status.
//   node scripts/shot-list.mjs
import { writeFile } from "node:fs/promises";
const { products } = await import("../src/content/products.ts");
const { foods } = await import("../src/content/foods.ts");
const { articles } = await import("../src/content/articles.ts");
const { tableObjects } = await import("../src/content/table.ts");
const en = (await import("../src/i18n/dictionaries/en.ts")).default;

const rows = [];
const add = (where, brief, done) => rows.push(`| ${where} | ${brief || "—"} | ${done ? "✅ licensed" : "⬜ needed"} |`);
tableObjects.forEach((o) => add(`The Table · ${o.scene} · ${o.label.en}`, o.brief + " Overhead cut-out.", Boolean(o.image)));
foods.forEach((f) => add(`Home · Food journal · ${f.content.en.name}`, f.content.en.brief, Boolean(f.image)));
["mother", "first-foods", "first-years"].forEach((k) => add(`Chapter · ${en.pillars[k].title} (hero + home index)`, en.pillars[k].imageBrief, false));
products.filter((p) => p.status !== "unpublished").forEach((p) => add(`Product · ${p.content.en.title}`, p.content.en.imageBrief, Boolean(p.image)));
articles.filter((a) => a.status === "published").forEach((a) => add(`Library · ${a.content.en.title}`, a.content.en.imageBrief, false));
add("About · Kitchen", "A lived-in kitchen in late afternoon: jars on the sill, a tea towel over a chair.", false);
add("About · Founder portrait", "Founder portrait, natural light (to be supplied by Ground & Mother).", false);

const md = `# Photography — shot list & licensing

Generated by \`node scripts/shot-list.mjs\`. Every image slot on the site, with the brief its placeholder shows.

## The Table (homepage)

One table, one camera, one light. Shoot everything from a fixed rig **directly overhead (90°)**, camera height and lens unchanged for the whole shoot, window light from the **upper left** of the frame.

1. **The table:** an empty-table plate at the highest resolution, with linen cloth, shot edge to edge (portrait and landscape framings).
2. **Each object:** shot alone on the same cloth in its place, then cut out to a transparent PNG/WebP. Keep its true shadow on a separate soft layer if possible; the site adds a matching contact shadow.
3. **Scale:** shoot a ruler once so every cut-out keeps its real size relative to the table.
4. **Food:** styled to be eaten: soft eggs, broth with a little steam, torn sourdough. No styling tricks that read as fake.
5. **Hands:** the toddler's hands should enter from the table edge, shot with a parent present (model release needed).

Add each file to \`public/images/table/\` and set its \`image\` in \`src/content/table.ts\`.

**Direction:** analog 35mm feel, natural window light, rich shadows, honest food, intimate family moments, earthy colour, subtle grain. No generic stock wellness imagery, no AI imagery, and no photograph used twice.

**How to add one:** \`node scripts/add-photo.mjs <url> <path/name.jpg> --credit … --source … --license …\`, then set the slot's \`image\` in the content file. Credits are kept in \`src/content/photo-credits.json\`.

**Not photographs:** the soil behind the opening scene is a procedural render (\`scripts/render-soil.py\`), and the seed, roots and shoot are drawn in SVG. Both are presented as illustration, never as photography.

| Slot | Brief | Status |
|---|---|---|
${rows.join("\n")}
`;
await writeFile("PHOTOGRAPHY.md", md);
console.log(`PHOTOGRAPHY.md: ${rows.length} slots.`);
